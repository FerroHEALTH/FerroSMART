//! The book's generated reference pages, each held to the code it is
//! rendered from: the command line from the `clap` definition of
//! [`Cli`](ferrosmart::cli::Cli), the administration API from the committed
//! OpenAPI document the router is held to, and the default configuration
//! from [`Config::default`](ferrosmart::config::Config).
//!
//! Each `the_book_holds_*` case fails when the committed page differs from
//! what the code renders; `write_the_reference_pages` (ignored, run with
//! `cargo nextest run -p ferrosmart --test it --run-ignored only
//! reference_pages`) writes every page again. No specification governs the
//! pages: our own design.

use std::fmt::Write as _;
use std::path::PathBuf;

use clap::{Command, CommandFactory as _};
use ferrosmart::cli::Cli;
use ferrosmart::config::Config;
use serde_json::Value;

/// The command line page.
const CLI: &str = "website/book/src/reference/cli.md";

/// The administration API page.
const ADMIN: &str = "website/book/src/reference/admin-operations.md";

/// The default configuration page.
const DEFAULTS: &str = "website/book/src/reference/default-configuration.md";

/// The help width, fixed so the page does not depend on the terminal.
const WIDTH: usize = 100;

/// The command that writes every page again.
const REWRITE: &str =
    "cargo nextest run -p ferrosmart --test it --run-ignored only reference_pages";

/// Returns the absolute path of the workspace file `relative`.
fn path(relative: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .join(relative)
}

// REUSE-IgnoreStart
/// Returns the banner and title every page opens with.
fn head(source: &str, title: &str, audience: &str) -> String {
    format!(
        "<!-- @generated by the ferrosmart test reference_pages from {source}. DO NOT EDIT. -->\n\
         <!-- SPDX-FileCopyrightText: Cadasto B.V. -->\n\
         <!-- SPDX-License-Identifier: BUSL-1.1 -->\n\n\
         # {title}\n\n\
         **For:** {audience}\n\n"
    )
}
// REUSE-IgnoreEnd

/// Appends the section of `command`, reached as `path`, and of each visible
/// subcommand below it.
fn section(out: &mut String, path: &str, command: &mut Command) {
    let help = command.render_long_help().to_string();
    for piece in ["## `", path, "`\n\n```text\n", help.trim_end(), "\n```\n\n"] {
        out.push_str(piece);
    }
    for sub in command
        .get_subcommands_mut()
        .filter(|sub| !sub.is_hide_set() && sub.get_name() != "help")
    {
        let below = [path, sub.get_name()].join(" ");
        section(out, &below, sub);
    }
}

/// The command line page the `clap` definition renders.
fn cli_page() -> String {
    let mut command = Cli::command().term_width(WIDTH).max_term_width(WIDTH);
    command.build();
    let mut out = head(
        "the clap definition of the ferrosmart binary",
        "Command-line reference",
        "operators. Every command and option of the `ferrosmart` binary, as\n\
         `ferrosmart <command> --help` prints it. What each command is for is on\n\
         [operate and monitor](../operate/operations.md#the-commands).",
    );
    section(&mut out, "ferrosmart", &mut command);
    out.trim_end().to_owned() + "\n"
}

/// Returns who may call an operation, from its OpenAPI `security`.
fn callers(operation: &Value) -> String {
    let Some(requirements) = operation.get("security").and_then(Value::as_array) else {
        return String::from("a token of `system/admin`");
    };
    if requirements.is_empty() {
        return String::from("anyone, without a token");
    }
    let named: Vec<String> = requirements
        .iter()
        .filter_map(Value::as_object)
        .map(|requirement| {
            if requirement.is_empty() {
                return String::from("an app registering itself, when registration is open");
            }
            requirement
                .iter()
                .map(|(scheme, scopes)| {
                    let scopes: Vec<String> = scopes
                        .as_array()
                        .into_iter()
                        .flatten()
                        .filter_map(Value::as_str)
                        .map(|scope| format!("`{scope}`"))
                        .collect();
                    match scheme.as_str() {
                        "registrationToken" => {
                            String::from("the client's registration access token")
                        }
                        _ => format!("a token of {}", scopes.join(", ")),
                    }
                })
                .collect::<Vec<_>>()
                .join(" and ")
        })
        .collect();
    named.join("; or ")
}

/// The administration API page the committed OpenAPI document renders.
fn admin_page() -> String {
    let text = std::fs::read_to_string(path("app/ferrosmart/openapi.json"))
        .expect("the OpenAPI document reads");
    let document: Value = serde_json::from_str(&text).expect("the OpenAPI document is JSON");
    let mut out = head(
        "app/ferrosmart/openapi.json",
        "Admin API operations",
        "administrators and the tools they write. Every operation of the\n\
         administration API, client registration and the audit records, as the\n\
         OpenAPI document at `GET {issuer}/admin/openapi.json` describes them.\n\
         [The admin API](../configure/admin-api.md) explains each.",
    );
    out.push_str("| Operation | What it does | Who may call it | Answers |\n|---|---|---|---|\n");
    let paths = document
        .get("paths")
        .and_then(Value::as_object)
        .expect("the document has paths");
    for (route, item) in paths {
        let Some(item) = item.as_object() else {
            continue;
        };
        for method in ["get", "post", "put", "delete"] {
            let Some(operation) = item.get(method) else {
                continue;
            };
            let summary = operation
                .get("summary")
                .and_then(Value::as_str)
                .unwrap_or_default();
            let answers: Vec<String> = operation
                .get("responses")
                .and_then(Value::as_object)
                .into_iter()
                .flat_map(|responses| responses.keys())
                .map(|status| format!("`{status}`"))
                .collect();
            writeln!(
                out,
                "| `{} {route}` | {summary} | {} | {} |",
                method.to_uppercase(),
                callers(operation),
                answers.join(", ")
            )
            .expect("a string takes a row");
        }
    }
    out
}

/// The default configuration page [`Config::default`] renders.
fn defaults_page() -> String {
    let toml = toml::to_string(&Config::default()).expect("the default configuration is TOML");
    let mut out = head(
        "Config::default",
        "Default configuration",
        "operators. Every key FerroSMART reads with a default, at that default,\n\
         as the configuration tree holds it before a file, the environment or\n\
         `--set` change it. A table with no default, such as\n\
         `[[ferrosmart.upstream]]`, is absent here; [configuration](../configure/configuration.md)\n\
         and [upstream configuration](../configure/upstream-keys.md) describe every\n\
         key.",
    );
    for piece in ["```toml\n", toml.trim_end(), "\n```\n"] {
        out.push_str(piece);
    }
    out
}

/// Every page with its path.
fn pages() -> [(&'static str, String); 3] {
    [
        (CLI, cli_page()),
        (ADMIN, admin_page()),
        (DEFAULTS, defaults_page()),
    ]
}

/// Asserts the committed page at `relative` is `rendered`.
fn holds(relative: &str, rendered: &str) {
    let committed = std::fs::read_to_string(path(relative)).expect("the reference page reads");
    assert!(
        committed == rendered,
        "{relative} is out of date: run `{REWRITE}` and commit the page"
    );
}

#[test]
fn the_book_holds_the_current_cli_reference() {
    holds(CLI, &cli_page());
}

#[test]
fn the_book_holds_the_current_admin_operations() {
    holds(ADMIN, &admin_page());
}

#[test]
fn the_book_holds_the_current_default_configuration() {
    holds(DEFAULTS, &defaults_page());
}

#[test]
#[ignore = "writes the book's reference pages; run on purpose after changing their source"]
fn write_the_reference_pages() {
    for (relative, page) in pages() {
        std::fs::write(path(relative), page).expect("the reference page is written");
    }
}
